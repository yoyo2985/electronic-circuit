        if (!rst_n) begin
            st        <= S_LOAD;
            cnt       <= {LOGN{1'b0}};
            m         <= {LOGM{1'b0}};
            k         <= {LOGN{1'b0}};
            acc       <= 64'd0;
            accn      <= 64'd0;
            prod      <= 64'd0;
            out_valid <= 1'b0;
            out_mel   <= 64'd0;
        end else begin
            out_valid <= 1'b0;
            case (st)
                S_LOAD: begin
                    if (in_valid) begin
                        pow[cnt] <= in_pow;
                        if (cnt == NBM1) begin
                            cnt <= {LOGN{1'b0}};
                            m   <= {LOGM{1'b0}};
                            k   <= {LOGN{1'b0}};
                            acc <= 64'd0;
                            st  <= S_CALC;
                        end else cnt <= cnt + 1'b1;
                    end
                end
                S_CALC: begin
                    prod = pow[k] * coef_fn(m*NB + k);
                    accn = acc + prod;
                    if (k == NBM1) begin
                        out_mel   <= accn >> CFQ;
                        out_valid <= 1'b1;
